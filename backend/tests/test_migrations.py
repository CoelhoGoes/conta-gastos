def test_lancamentos_existentes_ganham_o_id_da_categoria(monkeypatch):
    """UC9: cada lançamento passa a apontar para a categoria de mesmo tipo e nome — "Outros"
    de gasto e de entrada são linhas diferentes. O downgrade devolve o texto."""
    config, command, engine = _ate_antes_das_categorias(monkeypatch)
    try:
        with engine.begin() as conn:
            conn.execute(text("""
                INSERT INTO lancamentos (usuario_id, tipo, valor, descricao, categoria, data, forma, parcelas)
                VALUES (1, 'gasto', 10, 'a', 'Mercado', '2026-09-03', 'avista', 1),
                       (1, 'gasto', 10, 'b', 'Outros', '2026-09-03', 'avista', 1),
                       (1, 'entrada', 10, 'c', 'Outros', '2026-09-03', 'avista', 1)
            """))
        command.upgrade(config, "head")
        with engine.begin() as conn:
            ligados = conn.execute(text("""
                SELECT l.descricao, c.tipo, c.nome FROM lancamentos l
                JOIN categorias c ON c.id = l.categoria_id ORDER BY l.descricao
            """)).all()
        assert ligados == [("a", "gasto", "Mercado"), ("b", "gasto", "Outros"), ("c", "entrada", "Outros")]

        command.downgrade(config, "6f1a02b20a81")
        with engine.begin() as conn:
            textos = conn.execute(text("SELECT categoria FROM lancamentos ORDER BY descricao")).scalars().all()
        assert textos == ["Mercado", "Outros", "Outros"]
    finally:
        engine.dispose()
        _empty_database()


def test_lancamento_sem_categoria_correspondente_impede_a_migracao(monkeypatch):
    """F11: nada é reescrito em silêncio — a migração para e diz qual par não casou."""
    config, command, engine = _ate_antes_das_categorias(monkeypatch)
    try:
        with engine.begin() as conn:
            conn.execute(text("""
                INSERT INTO lancamentos (usuario_id, tipo, valor, descricao, categoria, data, forma, parcelas)
                VALUES (1, 'gasto', 10, 'a', 'Viagem', '2026-09-03', 'avista', 1),
                       (1, 'entrada', 10, 'b', 'Mercado', '2026-09-03', 'avista', 1)
            """))
        with pytest.raises(RuntimeError, match="entrada/Mercado, gasto/Viagem"):
            command.upgrade(config, "head")
        with engine.begin() as conn:
            assert conn.execute(text("SELECT categoria FROM lancamentos ORDER BY descricao")).scalars().all() == [
                "Viagem", "Mercado"
            ]
    finally:
        engine.dispose()
        _empty_database()


def _database_names(engine):
    """Nomes de constraints e índices do banco, por tabela, fora a tabela do Alembic. O
    índice que sustenta uma PK ou única tem o nome dela, então os dois viram um item só."""
    with engine.begin() as conn:
        constraints = conn.execute(text("""
            SELECT conrelid::regclass::text, conname FROM pg_constraint
            WHERE connamespace = 'public'::regnamespace
        """)).all()
        indexes = conn.execute(text("""
            SELECT tablename, indexname FROM pg_indexes WHERE schemaname = 'public'
        """)).all()
    names = set(constraints) | set(indexes)
    return {(t, n) for t, n in names if t != "alembic_version"}


def _model_names():
    import app.infra.models  # noqa: F401
    from app.infra.database import Base

    names = set()
    for table in Base.metadata.sorted_tables:
        for item in [*table.constraints, *table.indexes]:
            assert item.name, f"{table.name}: {item!r} sem nome — a convenção não cobriu"
            names.add((table.name, str(item.name)))
    return names


def test_nomes_no_banco_sao_os_do_modelo(monkeypatch):
    """UC5: o `alembic check` não compara nome de PK e FK — esta é a guarda. Também cobre o
    UC1 (toda constraint do modelo tem nome) e o UC3 (banco montado do zero)."""
    _, _, engine = _migrated_to(monkeypatch, "head")
    try:
        assert _database_names(engine) == _model_names()
    finally:
        engine.dispose()
        _empty_database()


def test_renomear_mantem_os_dados_e_volta(monkeypatch):
    """UC2 e UC4: um banco com dados ganha os nomes do padrão e, no downgrade, os antigos."""
    config, command, engine = _migrated_to(monkeypatch, "98844844bbad")
    try:
        antes = _database_names(engine)
        with engine.begin() as conn:
            conn.execute(text("""
                INSERT INTO usuarios (id, email, senha_hash, dia_fechamento) VALUES (1, 'a@b.co', 'x', 10);
                INSERT INTO lancamentos (usuario_id, tipo, valor, descricao, categoria_id, data, forma, parcelas)
                SELECT 1, 'gasto', 10, 'a', id, '2026-09-03', 'avista', 1 FROM categorias
                WHERE tipo = 'gasto' AND nome = 'Mercado';
                INSERT INTO rendas (id, usuario_id, inicio) VALUES (1, 1, '2026-01-01');
                INSERT INTO partes_renda (renda_id, valor, mes_seguinte) VALUES (1, 3000, false);
            """))
        contagem = "SELECT (SELECT count(*) FROM lancamentos), (SELECT count(*) FROM partes_renda)"

        command.upgrade(config, "head")
        assert _database_names(engine) == _model_names()
        with engine.begin() as conn:
            assert conn.execute(text(contagem)).one() == (1, 1)

        command.downgrade(config, "98844844bbad")
        assert _database_names(engine) == antes
        with engine.begin() as conn:
            assert conn.execute(text(contagem)).one() == (1, 1)
    finally:
        engine.dispose()
        _empty_database()


def test_nome_inesperado_impede_a_migracao(monkeypatch):
    """F1: um banco com nome diferente do esperado não sai com metade dos nomes trocados."""
    config, command, engine = _migrated_to(monkeypatch, "98844844bbad")
    try:
        with engine.begin() as conn:
            conn.execute(text("ALTER TABLE rendas RENAME CONSTRAINT rendas_pkey TO outro_nome"))
        antes = _database_names(engine)
        with pytest.raises(RuntimeError, match="rendas_pkey"):
            command.upgrade(config, "head")
        assert _database_names(engine) == antes
    finally:
        engine.dispose()
        _empty_database()

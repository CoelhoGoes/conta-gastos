"""As migrações chegam ao mesmo schema que os modelos descrevem.

O resto da suíte cria as tabelas a partir dos modelos (`create_all`), então um modelo alterado
sem migração passa em todos os outros testes e só quebra no deploy. Este teste sobe as
migrações num banco vazio e roda o `alembic check`.

Só roda contra Postgres (`TEST_DATABASE_URL`): as migrações foram geradas para ele e não
rodam em sqlite. No dia a dia, quem faz essa conferência é o `./dev.sh`.
"""

import os
import sys
from pathlib import Path

import pytest
from sqlalchemy import create_engine, text

URL = os.getenv("TEST_DATABASE_URL")
BACKEND = Path(__file__).resolve().parent.parent

pytestmark = pytest.mark.skipif(not URL, reason="as migrações só rodam em Postgres")


def _empty_database():
    """Nem tabela dos modelos nem marca de versão do Alembic — os outros testes deixam as duas."""
    import app.infra.models  # noqa: F401 — sem isto o metadata está vazio e o drop_all não apaga nada
    from app.infra.database import Base

    engine = create_engine(URL)
    Base.metadata.drop_all(bind=engine)
    with engine.begin() as conn:
        conn.execute(text("DROP TABLE IF EXISTS alembic_version"))
    engine.dispose()


def _migrated_to(monkeypatch, revision):
    """Banco vazio migrado até `revision`. Devolve o config e o `command` do Alembic, para o
    teste seguir migrando, e um engine para inserir e consultar."""
    from alembic.config import Config

    from alembic import command

    # o env.py lê a URL de app.infra.database, que a captura no import: recarrega apontando para cá
    monkeypatch.setenv("DATABASE_URL", URL)
    for mod in [m for m in sys.modules if m == "app" or m.startswith("app.")]:
        del sys.modules[mod]

    config = Config(str(BACKEND / "alembic.ini"))
    config.set_main_option("script_location", str(BACKEND / "alembic"))
    _empty_database()
    command.upgrade(config, revision)
    return config, command, create_engine(URL)


def test_migracoes_e_modelos_descrevem_o_mesmo_schema(monkeypatch):
    config, command, engine = _migrated_to(monkeypatch, "head")
    try:
        # levanta AutogenerateDiffsDetected quando modelo e migração divergem
        command.check(config)
    finally:
        engine.dispose()
        _empty_database()


def test_renda_das_contas_existentes_vira_historico(monkeypatch):
    """UC9: a renda configurada passa a valer do mês do primeiro lançamento (ou da criação da
    conta, sem lançamento), para o saldo do mês dos meses passados não mudar. Renda 0 não vira
    registro."""
    # a última antes do histórico da renda
    config, command, engine = _migrated_to(monkeypatch, "327f8230f60a")
    try:
        with engine.begin() as conn:
            conn.execute(text("""
                INSERT INTO usuarios (id, email, senha_hash, renda_mensal, dia_fechamento, criado_em)
                VALUES (1, 'com@b.co', 'x', 5000, 10, '2026-01-15'),
                       (2, 'sem@b.co', 'x', 3000, 10, '2026-03-20'),
                       (3, 'zero@b.co', 'x', 0, 10, '2026-01-01')
            """))
            conn.execute(text("""
                INSERT INTO lancamentos (usuario_id, tipo, valor, descricao, categoria, data, forma, parcelas)
                VALUES (1, 'gasto', 10, 'b', 'Outros', '2026-09-03', 'avista', 1),
                       (1, 'gasto', 10, 'a', 'Outros', '2026-07-21', 'avista', 1),
                       (3, 'gasto', 10, 'c', 'Outros', '2026-05-01', 'avista', 1)
            """))
        command.upgrade(config, "580bb2fb1f8d")
        with engine.begin() as conn:
            rendas = conn.execute(
                text("SELECT usuario_id, mes::text, valor::text FROM rendas ORDER BY usuario_id")
            ).all()
        assert rendas == [(1, "2026-07-01", "5000.00"), (2, "2026-03-01", "3000.00")]
    finally:
        engine.dispose()
        _empty_database()


def test_rendas_antigas_ganham_fim_e_viram_uma_parte_sem_dia(monkeypatch):
    """F8: a renda valia até começar a próxima; esse fim vira explícito, para as antigas não
    passarem a se somar. A renda vira uma parte sem regra (UC10), e a renda 0 sai — o fim da
    anterior já diz que a pessoa parou de receber."""
    # a última antes do dia de pagamento
    config, command, engine = _migrated_to(monkeypatch, "580bb2fb1f8d")
    try:
        with engine.begin() as conn:
            conn.execute(text("""
                INSERT INTO usuarios (id, email, senha_hash, dia_fechamento, criado_em)
                VALUES (1, 'a@b.co', 'x', 10, '2026-01-01'), (2, 'b@b.co', 'x', 10, '2026-01-01')
            """))
            conn.execute(text("""
                INSERT INTO rendas (usuario_id, mes, valor)
                VALUES (1, '2026-01-01', 3000), (1, '2026-05-01', 4000), (1, '2026-08-01', 0),
                       (1, '2026-10-01', 5000), (2, '2026-03-01', 2000)
            """))
        command.upgrade(config, "head")
        with engine.begin() as conn:
            rendas = conn.execute(text("""
                SELECT r.usuario_id, r.inicio::text, r.fim::text, p.valor::text, p.regra,
                       p.mes_seguinte
                FROM rendas r JOIN partes_renda p ON p.renda_id = r.id
                ORDER BY r.usuario_id, r.inicio
            """)).all()
            sobra = conn.execute(text("SELECT count(*) FROM rendas")).scalar()
        assert rendas == [
            (1, "2026-01-01", "2026-04-30", "3000.00", None, False),
            (1, "2026-05-01", "2026-07-31", "4000.00", None, False),
            (1, "2026-10-01", None, "5000.00", None, False),
            (2, "2026-03-01", None, "2000.00", None, False),
        ]
        assert sobra == 4  # a renda 0 de agosto saiu
    finally:
        engine.dispose()
        _empty_database()


